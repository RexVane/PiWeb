const dicts: Record<string, Dict> = { zh, en };

interface I18nCtx {
	lang: "zh" | "en";
	setLang: (l: "zh" | "en") => void;
	t: Dict;
}

const Ctx = createContext<I18nCtx>({ lang: "zh", setLang: () => {}, t: zh });

export function I18nProvider({ children }: { children: React.ReactNode }) {
	const [lang, setLangState] = useState<"zh" | "en">("zh");
	useEffect(() => {
		const saved = localStorage.getItem("piweb.lang");
		if (saved === "en" || saved === "zh") setLangState(saved);
	}, []);
	useEffect(() => {
		document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
	}, [lang]);
	const setLang = useCallback((l: "zh" | "en") => {
		setLangState(l);
		localStorage.setItem("piweb.lang", l);
	}, []);
	return <Ctx.Provider value={{ lang, setLang, t: dicts[lang] }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
	return useContext(Ctx);
}
