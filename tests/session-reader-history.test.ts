import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { recycleFixture } from "./fixtures/recycle";
vi.mock("../src/lib/growth-tracker", () => ({ GROWTH_TRACKER_VERSION: 1, createGrowthTracker: () => ({ version: 1, prepare: async () => {}, onEvent: () => {}, getError: () => null, dispose: () => {} }) }));
let root: string | undefined;
let managed: ReturnType<typeof import("../src/lib/agent-manager")["getManaged"]> | undefined;
afterEach(async () => {
	if (managed) await (await import("../src/lib/agent-manager")).disposeSession(managed);
	vi.unstubAllEnvs();
	if (root) await recycleFixture(root);
});
it("cold reads return a bounded recent page with authenticated image URLs and leave the authoritative JSONL intact", async () => {
	root = await fs.mkdtemp(path.join(os.tmpdir(), "piweb-cold-history-"));
	const agentDir = path.join(root, "agent"), cwd = path.join(root, "workspace");
	await fs.mkdir(agentDir); await fs.mkdir(cwd);
	vi.stubEnv("PI_CODING_AGENT_DIR", agentDir); vi.stubEnv("PI_OFFLINE", "1");
	const { SessionManager, encodeSessionId } = await import("../src/lib/pi");
	const { getManaged } = await import("../src/lib/agent-manager");
	const { readSession } = await import("../src/lib/session-reader");
	const sm = SessionManager.create(cwd);
	for (let index = 0; index < 180; index++) sm.appendMessage({ role: "user", content: "history-" + index, timestamp: index + 1 });
	const originalText = "original-large-text:" + "x".repeat(1024 * 1024);
	sm.appendMessage({ role: "user", content: [{ type: "text", text: originalText }, { type: "image", data: "iVBORw0KGgo=", mimeType: "image/png" }], timestamp: 200 });
	const file = sm.getSessionFile()!;
	const result = await readSession(file);
	managed = getManaged(file);
	expect(managed.session).toBeFalsy();
	expect(result.messages.length).toBeLessThanOrEqual(100);
	expect(result.historyPage.total).toBeGreaterThan(100);
	expect(result.historyPage.olderBefore).toBeGreaterThan(0);
	expect(Buffer.byteLength(JSON.stringify(result))).toBeLessThanOrEqual(5 * 1024 * 1024);
	const image = result.messages.at(-1)!.content.find((part) => part.type === "image");
	expect(image).toMatchObject({ type: "image", data: "", url: expect.stringContaining("/api/sessions/" + encodeSessionId(file) + "/images?") });
	expect(result.messages.at(-1)!.truncated).toBe(true);
	expect(await fs.readFile(file, "utf8")).toContain(originalText);
});

it("cold history refreshes same-size rewrites of import metadata without starting the agent", async () => {
	root = await fs.mkdtemp(path.join(os.tmpdir(), "piweb-cold-history-rewrite-"));
	const agentDir = path.join(root, "agent"), cwd = path.join(root, "workspace");
	await fs.mkdir(agentDir); await fs.mkdir(cwd);
	vi.stubEnv("PI_CODING_AGENT_DIR", agentDir); vi.stubEnv("PI_OFFLINE", "1");
	const { SessionManager } = await import("../src/lib/pi");
	const { getManaged } = await import("../src/lib/agent-manager");
	const { readSession } = await import("../src/lib/session-reader");
	const sm = SessionManager.create(cwd);
	sm.appendMessage({ role: "user", content: "original question", timestamp: 1 });
	sm.appendCustomEntry("piweb-import", { source: "claude" });
	const notification = "<task-notification><task-id>task-1</task-id><status>killed</status><summary>Background server stopped</summary></task-notification>";
	sm.appendMessage({ role: "user", content: notification, timestamp: 2 });
	const file = sm.getSessionFile()!;
	const first = await readSession(file);
	managed = getManaged(file);
	expect(first.messages.some((message) => message.content.some((part) => part.type === "text" && part.text === notification))).toBe(false);
	const original = await fs.readFile(file, "utf8");
	const replaced = original.replace('"source":"claude"', '"source":"codex" ');
	expect(replaced).not.toBe(original);
	expect(Buffer.byteLength(replaced)).toBe(Buffer.byteLength(original));
	await fs.writeFile(file, replaced);
	await fs.utimes(file, new Date(), new Date(Date.now() + 1000));
	const second = await readSession(file);
	managed = getManaged(file);
	expect(second.messages.some((message) => message.content.some((part) => part.type === "text" && part.text === notification))).toBe(true);
	expect(managed.session).toBeFalsy();
	expect(await fs.readFile(file, "utf8")).toBe(replaced);
});
